// Package install puts the plugin on a node: the binary the container runtime
// executes and the kubeconfig that binary uses when it runs in its own
// process. Both the node daemon and the thin entrypoint use it, so one
// DaemonSet container can install the plugin and then serve it, the way the
// ovn-kubernetes node container installs its CNI before running.
package install

import (
	"context"
	"encoding/base64"
	"fmt"
	"io"
	"net"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// BinaryName is the file name the container runtime looks for in its CNI
// binary directory; it matches the plugin's "type".
const BinaryName = "ib-sriov"

// ServiceAccountDir is the in-pod service-account mount. A var so tests can
// redirect it.
var ServiceAccountDir = "/var/run/secrets/kubernetes.io/serviceaccount"

const (
	kubeconfigFileName = "ib-sriov-cni.kubeconfig"
	kubeconfigSubDir   = "ib-sriov-cni.d"
	kubeconfigFileMode = 0o600
	kubeconfigDirMode  = 0o750
	// KubeconfigRefreshInterval keeps the host kubeconfig ahead of bound
	// service account token rotation.
	KubeconfigRefreshInterval = 10 * time.Minute
	kubeconfigTemplate        = `# Generated by ib-sriov-cni. Do not edit.
apiVersion: v1
kind: Config
clusters:
- name: local
  cluster:
    server: %s
    certificate-authority-data: %s
users:
- name: ib-sriov-cni
  user:
    token: "%s"
contexts:
- name: ib-sriov-cni-context
  context:
    cluster: local
    user: ib-sriov-cni
current-context: ib-sriov-cni-context
`
)

// execBits is any execute permission; a source without one would be installed
// as a plugin the runtime cannot exec.
const execBits = 0o111

// CopyBinary installs src as <dir>/ib-sriov, atomically and with src's mode,
// so a runtime that execs the plugin mid-copy sees the old file or the new one
// and never a partial one. dir must already exist: it is the host's CNI
// binary directory bind-mounted into the container, and creating it here
// would silently install into the container instead.
func CopyBinary(src, dir string) (string, error) {
	info, err := os.Stat(dir)
	if err != nil || !info.IsDir() {
		return "", fmt.Errorf("CNI bin directory %q is not present (is the hostPath mounted?): %v", dir, err)
	}
	in, err := os.Open(src) // #nosec G304 -- operator-selected source, this binary or the image's copy of it.
	if err != nil {
		return "", err
	}
	defer in.Close()
	srcInfo, err := in.Stat()
	if err != nil {
		return "", err
	}
	if !srcInfo.Mode().IsRegular() {
		return "", fmt.Errorf("plugin binary %q is not a regular file", src)
	}
	if srcInfo.Mode().Perm()&execBits == 0 {
		return "", fmt.Errorf("plugin binary %q is not executable", src)
	}
	dst := filepath.Join(dir, BinaryName)
	tmp := dst + ".temp"
	out, err := os.Create(tmp) // #nosec G304 -- inside the operator-selected CNI bin directory.
	if err != nil {
		return "", err
	}
	defer func() { _ = os.Remove(tmp) }()
	if _, err = io.Copy(out, in); err != nil {
		_ = out.Close()
		return "", err
	}
	if err = out.Sync(); err != nil {
		_ = out.Close()
		return "", err
	}
	if err := out.Close(); err != nil {
		return "", err
	}
	if err := os.Chmod(tmp, srcInfo.Mode()); err != nil {
		return "", err
	}
	if err := os.Rename(tmp, dst); err != nil {
		return "", err
	}
	return dst, nil
}

// APIServerURL builds the in-cluster apiserver URL. IPv6 hosts are bracketed;
// IPv4 and hostnames are not, because client-go rejects bracketed IPv4.
func APIServerURL() (string, error) {
	host := os.Getenv("KUBERNETES_SERVICE_HOST")
	port := os.Getenv("KUBERNETES_SERVICE_PORT")
	if host == "" || port == "" {
		return "", fmt.Errorf("KUBERNETES_SERVICE_HOST/PORT not set (not running in a pod?)")
	}
	if ip := net.ParseIP(host); ip != nil && ip.To4() == nil && strings.Contains(host, ":") {
		host = "[" + host + "]"
	}
	return "https://" + host + ":" + port, nil
}

// KubeconfigPath is where WriteKubeconfig puts the file under cniConfDir, and
// where the plugin looks for it by default.
func KubeconfigPath(cniConfDir string) string {
	return filepath.Join(cniConfDir, kubeconfigSubDir, kubeconfigFileName)
}

// WriteKubeconfig writes a kubeconfig under cniConfDir, the host's
// /etc/cni/net.d bind-mount, from this pod's service account token and CA, so
// the host-invoked plugin reaches the apiserver with the DaemonSet's identity.
func WriteKubeconfig(cniConfDir string) (string, error) {
	token, err := os.ReadFile(filepath.Join(ServiceAccountDir, "token"))
	if err != nil {
		return "", fmt.Errorf("failed to read service account token: %v", err)
	}
	ca, err := os.ReadFile(filepath.Join(ServiceAccountDir, "ca.crt"))
	if err != nil {
		return "", fmt.Errorf("failed to read service account CA: %v", err)
	}
	server, err := APIServerURL()
	if err != nil {
		return "", err
	}
	// If cniConfDir is absent the hostPath volume was not mounted; MkdirAll
	// would then create a container-local directory and the host-invoked
	// plugin would never find the kubeconfig while the Pod reports success.
	if info, statErr := os.Stat(cniConfDir); statErr != nil || !info.IsDir() {
		return "", fmt.Errorf("CNI conf dir %s not present (is the /etc/cni/net.d hostPath mounted?): %v",
			cniConfDir, statErr)
	}
	dst := KubeconfigPath(cniConfDir)
	if err := os.MkdirAll(filepath.Dir(dst), kubeconfigDirMode); err != nil {
		return "", fmt.Errorf("failed to create %s: %v", filepath.Dir(dst), err)
	}
	content := fmt.Sprintf(kubeconfigTemplate, server,
		base64.StdEncoding.EncodeToString(ca), strings.TrimSpace(string(token)))
	tmp := dst + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), kubeconfigFileMode); err != nil {
		return "", fmt.Errorf("failed to write %s: %v", tmp, err)
	}
	if err := os.Rename(tmp, dst); err != nil {
		_ = os.Remove(tmp) // never leave the token-bearing temp file on the host
		return "", fmt.Errorf("failed to move kubeconfig into place: %v", err)
	}
	return dst, nil
}

// RefreshKubeconfig rewrites the kubeconfig every interval until ctx ends,
// reporting each failure through report and carrying on: a token that rotates
// under a stale file would break every in-process plugin call on the node.
func RefreshKubeconfig(ctx context.Context, cniConfDir string, interval time.Duration, report func(error)) {
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			if _, err := WriteKubeconfig(cniConfDir); err != nil && report != nil {
				report(err)
			}
		}
	}
}
